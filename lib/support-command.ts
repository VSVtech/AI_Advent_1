// /support [TCK-1234] <вопрос> — ассистент поддержки: отвечает по FAQ (RAG) и
// данным тикета и пользователя (MCP «Поддержка»).
export const SUPPORT_DEFAULT_QUESTION =
  'Почему у пользователя не получается войти и что ему сделать?';
const TICKET_IN_TEXT = /\bTCK-\d{4,6}\b/iu;

export const SUPPORT_PROMPT = [
  'Команда /support: ты — ассистент службы поддержки продукта. Ответ предназначен для сотрудника поддержки, который отвечает пользователю.',
  'Решай по фактам, а не по общим предположениям:',
  '1. Если назван тикет, вызови get_ticket, затем get_user по userId из тикета и get_auth_events по тому же userId. Если тикета нет, но есть userId, начни с get_user.',
  '2. Найди в журнале событий причину и сопоставь её с фрагментами FAQ из RAG_CONTEXT. Опирайся на FAQ-документ docs/support/faq.md и называй его в ответе; фрагменты исходного кода для ответа пользователю не используй.',
  '3. Если вопрос тикета не про авторизацию (например, возврат оплаты), не проверяй журнал входа и не предлагай сброс пароля: отвечай по соответствующему разделу FAQ.',
  'Не выдумывай данные: если тикета, пользователя или события нет, скажи об этом. Не обещай сроки и действия, которых нет в FAQ. Не раскрывай данные других пользователей.',
  'Формат ответа: «Причина» (1-2 предложения с ссылкой на событие и его время), «Что сделать пользователю» (шаги), «Черновик ответа пользователю» (вежливо, на «вы», без технических кодов).',
].join('\n');

export function parseSupportCommand(content: string): string | null {
  const match = /^\/support(?:\s+([\s\S]*))?$/iu.exec(content.trim());
  if (!match) return null;
  const text = match[1]?.trim() ?? '';
  const ticket = TICKET_IN_TEXT.exec(text)?.[0].toUpperCase();
  const question = text.replace(TICKET_IN_TEXT, '').replace(/\s+/gu, ' ').trim();
  const asked = question || SUPPORT_DEFAULT_QUESTION;
  return ticket
    ? `Тикет ${ticket}. Вопрос сотрудника поддержки: ${asked}`
    : `Вопрос сотрудника поддержки (тикет не указан): ${asked}`;
}
